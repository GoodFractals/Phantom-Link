#requires -Version 5.1
<#
.SYNOPSIS
    Provision a Phantom Link pair: generate SSID/password, enroll the AP BSSID,
    rebuild both UF2s, and optionally flash them.

.DESCRIPTION
    Keeps the camouflage SSID style while making each pair unique and bound to
    the intended AP hardware address. Writes only firmware/proto/netcfg_local.h
    (generated, safe to overwrite). Never touches README or protocol code.
#>
[CmdletBinding()]
param(
    [string]$ApPort = 'COM5',
    [string]$StaPort = 'COM4',
    [string]$Repo = 'C:\Users\Windows 10\OneDrive\Desktop\Phantom_Link',
    [string]$ApSerial = '07A06CFD644C1FC9',
    [string]$StaSerial = '0AC087FCD9AAE588',
    [switch]$Flash
)

$ErrorActionPreference = 'Stop'
$header = Join-Path $Repo 'firmware\proto\netcfg_local.h'
$buildDir = Join-Path $Repo 'firmware\build'
$pt = 'C:\Users\Windows 10\.pico-sdk\picotool\2.3.1\picotool\picotool.exe'

function Read-BootLine([string]$port, [string]$pattern, [int]$seconds) {
    $sp = New-Object System.IO.Ports.SerialPort($port, 115200)
    $sp.DtrEnable = $true
    $sp.ReadTimeout = 1000
    try {
        $sp.Open() | Out-Null
        Start-Sleep -Seconds $seconds
        $text = ''
        while ($sp.BytesToRead -gt 0) { $text += $sp.ReadExisting() }
        $line = $text -split "`r?`n" | Where-Object { $_ -match $pattern } | Select-Object -Last 1
        return $line
    }
    finally { if ($sp.IsOpen) { $sp.Close() } }
}

Write-Host '=== Phantom Link pair provisioning ==='
Write-Host 'Power-cycle BOTH boards now so the AP prints its BSSID.'
Read-Host 'Press Enter when both boards are freshly plugged in' | Out-Null

$line = Read-BootLine $ApPort 'AP BSSID:\s+([0-9a-fA-F]{2}(?::[0-9a-fA-F]{2}){5})' 8
if (-not $line) { throw 'AP BSSID line not found on AP serial.' }
$bssid = ([regex]::Match($line, '([0-9a-fA-F]{2}(?::[0-9a-fA-F]{2}){5})')).Groups[1].Value
$bytes = $bssid.Split(':') | ForEach-Object { '0x' + $_.ToUpper() }
$bssidInit = ($bytes -join ', ')

$suffix = -join ((1..4) | ForEach-Object { '0123456789'[(Get-Random -Maximum 10)] })
$ssid = "TMOBILE-$suffix"
$password = -join ((1..16) | ForEach-Object { 'abcdefghjkmnpqrstuvwxyzABCDEFGHJKMNPQRSTUVWXYZ23456789'[(Get-Random -Maximum 56)] })

Write-Host ("SSID:     {0}" -f $ssid)
Write-Host ("Password: {0}" -f $password)
Write-Host ("BSSID:    {0}" -f $bssid)

$content = @"
// Generated by tools/provision_pair.ps1 — safe to regenerate.

#define PHANTOM_WIFI_SSID "$ssid"
#define PHANTOM_WIFI_PASSWORD "$password"
#define PHANTOM_AP_BSSID {$bssidInit}
"@
$enc = New-Object System.Text.UTF8Encoding($false)
[IO.File]::WriteAllText($header, $content, $enc)
Write-Host ("Wrote {0}" -f $header)

cmake --build $buildDir --parallel | Out-Null
if ($LASTEXITCODE -ne 0) { throw 'Build failed after provisioning.' }
Write-Host 'Build OK'

if ($Flash) {
    & (Join-Path $Repo 'tools\flash_pico.ps1') -Board ap -Flash | Out-Null
    & (Join-Path $Repo 'tools\flash_pico.ps1') -Board sta -Flash | Out-Null
    Write-Host 'Both boards flashed.'
}

Write-Host 'Provisioning complete. Power-cycle both boards to verify LINK UP.'
