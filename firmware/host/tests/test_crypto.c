static const uint8_t RFC4493_EMPTY[16] = {
    0xbb,0x1d,0x69,0x29,0xe9,0x59,0x37,0x28,0x7f,0xa3,0x7d,0x12,0x9b,0x75,0x67,0x46
};

static void test_aes_kat(void) {
    test_aes128_t aes;
    uint8_t zero[16] = {0}, out[16];
    static const uint8_t want[16] = {
        0x7d,0xf7,0x6b,0x0c,0x1a,0xb8,0x99,0xb3,
        0x3e,0x42,0xf0,0x47,0xb9,0x1b,0x54,0x6f
    };
    aes128_init(&aes, RFC4493_KEY);
    aes128_block(&aes, zero, out);
    CHECK(memcmp(out, want, sizeof out) == 0);
}

static void test_cmac_subkeys_rfc(void) {
    test_aes128_t aes;
    uint8_t k1[16], k2[16];
    aes128_init(&aes, RFC4493_KEY);
    pc_cmac_subkeys(aes128_block, &aes, k1, k2);
    CHECK(memcmp(k1, RFC4493_K1, sizeof k1) == 0);
    CHECK(memcmp(k2, RFC4493_K2, sizeof k2) == 0);
}

static void test_cmac_empty_rfc(void) {
    test_aes128_t aes;
    uint8_t tag[16];
    aes128_init(&aes, RFC4493_KEY);
    pc_cmac(aes128_block, &aes, NULL, 0, tag);
    CHECK(memcmp(tag, RFC4493_EMPTY, sizeof tag) == 0);
}

