/* NSA Simon & Speck paper, Appendix C, byte form (little-endian words). */
static const uint8_t KAT_A_KEY[16] = {
    0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07,
    0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f
};
static const uint8_t KAT_A_PT[16] = {
    0x20, 0x6d, 0x61, 0x64, 0x65, 0x20, 0x69, 0x74,
    0x20, 0x65, 0x71, 0x75, 0x69, 0x76, 0x61, 0x6c
};
static const uint8_t KAT_A_CT[16] = {
    0x18, 0x0d, 0x57, 0x5c, 0xdf, 0xfe, 0x60, 0x78,
    0x65, 0x32, 0x78, 0x79, 0x51, 0x98, 0x5d, 0xa6
};

static void test_speck_kat_a(void) {
    speck128_key_t key;
    uint8_t out[16];

    speck128_set_key(&key, KAT_A_KEY);
    speck128_encrypt(&key, KAT_A_PT, out);
    if (memcmp(out, KAT_A_CT, sizeof out) != 0) {
        printf("  got:");
        for (size_t i = 0; i < sizeof out; i++) printf(" %02x", out[i]);
        printf("\n");
    }
    CHECK(memcmp(out, KAT_A_CT, sizeof out) == 0);
}

