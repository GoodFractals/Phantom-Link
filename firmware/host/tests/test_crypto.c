static void test_cmac_lengths_rfc(void) {
    test_aes128_t aes;
    uint8_t tag[16], short_tag[PC_TAG_BYTES];

    aes128_init(&aes, RFC4493_KEY);

    pc_cmac(aes128_block, &aes, RFC4493_MSG, 16, tag);
    CHECK(memcmp(tag, RFC4493_TAG16, sizeof tag) == 0);

    pc_cmac(aes128_block, &aes, RFC4493_MSG, 40, tag);
    CHECK(memcmp(tag, RFC4493_TAG40, sizeof tag) == 0);

    pc_cmac(aes128_block, &aes, RFC4493_MSG, 64, tag);
    CHECK(memcmp(tag, RFC4493_TAG64, sizeof tag) == 0);

    pc_cmac_trunc(aes128_block, &aes, RFC4493_MSG, 64, short_tag);
    CHECK(memcmp(short_tag, RFC4493_TAG64, sizeof short_tag) == 0);
}

static void test_kdf_domain_separation(void) {
    static const uint8_t master[PC_MASTER_KEY_BYTES] = {
        0x00,0x01,0x02,0x03,0x04,0x05,0x06,0x07,0x08,0x09,0x0a,0x0b,0x0c,0x0d,0x0e,0x0f,
        0x10,0x11,0x12,0x13,0x14,0x15,0x16,0x17,0x18,0x19,0x1a,0x1b,0x1c,0x1d,0x1e,0x1f
    };
    static const uint8_t salt[] = { 'B','O','N','N','I','E','-','C','L','Y','D','E','-','v','1' };
    uint8_t send[PC_DERIVED_KEY_BYTES], recv[PC_DERIVED_KEY_BYTES];
    uint8_t again[PC_DERIVED_KEY_BYTES];
    uint8_t other_salt[sizeof salt], changed[PC_DERIVED_KEY_BYTES];

    pc_kdf(master, salt, sizeof salt, 0x01u, send);
    pc_kdf(master, salt, sizeof salt, 0x02u, recv);
    pc_kdf(master, salt, sizeof salt, 0x01u, again);
    memcpy(other_salt, salt, sizeof salt);
    other_salt[0] ^= 0x01u;
    pc_kdf(master, other_salt, sizeof other_salt, 0x01u, changed);

    CHECK(memcmp(send, recv, sizeof send) != 0);
    CHECK(memcmp(send, again, sizeof send) == 0);
    CHECK(memcmp(send, changed, sizeof send) != 0);
}

static void test_ctr_and_suite_round_trip(void) {
    static const uint8_t key[16] = {
        0x00,0x01,0x02,0x03,0x04,0x05,0x06,0x07,
        0x08,0x09,0x0a,0x0b,0x0c,0x0d,0x0e,0x0f
    };
    static const uint8_t nonce[PC_NONCE_BYTES] = {
        0x01,0x02,0x03,0x04,0x05,0x06,0x07,0x08,0x09,0x0a,0x0b,0x0c
    };
    static const uint8_t aad[18] = {
        0x42,0x43,0x01,0x02,0x00,0x00,0x11,0x22,0x33,0x44,
        0x00,0x00,0x00,0x05,0x00,0x00,0x00,0x00
    };
    uint8_t plain[21], wire[21];
    uint8_t tag[PC_TAG_BYTES];
    size_t i;

    for (i = 0; i < sizeof plain; i++) plain[i] = (uint8_t)(0xA0u + (uint8_t)i);
    memcpy(wire, plain, sizeof plain);

    pc_suite_speck_ctr_cmac.seal(key, nonce, aad, sizeof aad,
                                 wire, sizeof wire, tag);
    CHECK(memcmp(wire, plain, sizeof plain) != 0);

    CHECK(pc_suite_speck_ctr_cmac.open(key, nonce, aad, sizeof aad,
                                       wire, sizeof wire, tag) == 0);
    CHECK(memcmp(wire, plain, sizeof plain) == 0);

    tag[0] ^= 0x01u;
    CHECK(pc_suite_speck_ctr_cmac.open(key, nonce, aad, sizeof aad,
                                       wire, sizeof wire, tag) != 0);
    CHECK(pc_suite_aead.seal == NULL || pc_suite_aead.open == NULL);
}

static void test_key_confirmation(void) {
    static const uint8_t key_a[16] = {
        0x00,0x01,0x02,0x03,0x04,0x05,0x06,0x07,
        0x08,0x09,0x0a,0x0b,0x0c,0x0d,0x0e,0x0f
    };
    static const uint8_t key_b[16] = {
        0x10,0x11,0x12,0x13,0x14,0x15,0x16,0x17,
        0x18,0x19,0x1a,0x1b,0x1c,0x1d,0x1e,0x1f
    };
    static const uint8_t nonce[PC_CONFIRM_NONCE_BYTES] = {
        0xa1,0xa2,0xa3,0xa4,0xa5,0xa6,0xa7,0xa8
    };
    uint8_t tag[PC_CONFIRM_TAG_BYTES], bad[PC_CONFIRM_TAG_BYTES];
    const uint32_t session = 0x11223344u;

    pc_confirm_tag(key_a, 0x01u, session, 0u, nonce, tag);
    CHECK(pc_confirm_check(key_a, 0x01u, session, 0u, nonce, tag));
    CHECK(!pc_confirm_check(key_b, 0x01u, session, 0u, nonce, tag));
    CHECK(!pc_confirm_check(key_a, 0x02u, session, 0u, nonce, tag));
    CHECK(!pc_confirm_check(key_a, 0x01u, session + 1u, 0u, nonce, tag));
    memcpy(bad, tag, sizeof bad);
    bad[0] ^= 0x01u;
    CHECK(!pc_confirm_check(key_a, 0x01u, session, 0u, nonce, bad));
}

