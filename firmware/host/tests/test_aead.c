/* Suite ops, frame-sized AAD (18 bytes), round trip and tamper rejection.    */
/* ------------------------------------------------------------------------- */
static void test_suite_round_trip(void) {
    static const uint8_t key[AEAD_KEY_BYTES] = {
        0x00,0x01,0x02,0x03,0x04,0x05,0x06,0x07,
        0x08,0x09,0x0a,0x0b,0x0c,0x0d,0x0e,0x0f,
        0x10,0x11,0x12,0x13,0x14,0x15,0x16,0x17,
        0x18,0x19,0x1a,0x1b,0x1c,0x1d,0x1e,0x1f
    };
    static const uint8_t nonce[AEAD_NONCE_BYTES] = {
        0x01,0x02,0x03,0x04,0x05,0x06,0x07,0x08,0x09,0x0a,0x0b,0x0c
    };
    uint8_t aad[AEAD_AAD_BYTES] = {
        0x42,0x43,0x01,0x02,0x00,0x00,0x11,0x22,0x33,
        0x44,0x00,0x00,0x00,0x05,0x00,0x00,0x00,0x00
    };
    uint8_t plain[21], buf[21], tag[AEAD_TAG_BYTES];
    size_t i;

    CHECK(aead_suite_chacha20_poly1305.seal != NULL);
    CHECK(aead_suite_chacha20_poly1305.open != NULL);

    for (i = 0u; i < sizeof plain; i++) plain[i] = (uint8_t)(0xa0u + (uint8_t)i);
    memcpy(buf, plain, sizeof buf);

    aead_suite_chacha20_poly1305.seal(key, nonce, aad, sizeof aad,
                                      buf, sizeof buf, tag);
    CHECK(memcmp(buf, plain, sizeof buf) != 0);
    CHECK(aead_suite_chacha20_poly1305.open(key, nonce, aad, sizeof aad,
                                            buf, sizeof buf, tag) == 0);
    CHECK(memcmp(buf, plain, sizeof buf) == 0);
}

/* A rejected frame must be left untouched: the tag is verified before any
 * decryption is performed. */
static void test_verify_before_decrypt(void) {
    static const uint8_t key[AEAD_KEY_BYTES] = {
        0x00,0x01,0x02,0x03,0x04,0x05,0x06,0x07,
        0x08,0x09,0x0a,0x0b,0x0c,0x0d,0x0e,0x0f,
        0x10,0x11,0x12,0x13,0x14,0x15,0x16,0x17,
        0x18,0x19,0x1a,0x1b,0x1c,0x1d,0x1e,0x1f
    };
    static const uint8_t nonce[AEAD_NONCE_BYTES] = {
        0x01,0x02,0x03,0x04,0x05,0x06,0x07,0x08,0x09,0x0a,0x0b,0x0c
    };
    uint8_t aad[AEAD_AAD_BYTES], plain[21], wire[21], tag[AEAD_TAG_BYTES];
    uint8_t bad_tag[AEAD_TAG_BYTES], working[21];
    size_t i;

    for (i = 0u; i < sizeof aad; i++) aad[i] = (uint8_t)i;
    for (i = 0u; i < sizeof plain; i++) plain[i] = (uint8_t)(0x40u + (uint8_t)i);
    memcpy(wire, plain, sizeof wire);
    aead_seal(key, nonce, aad, sizeof aad, wire, sizeof wire, tag);

    memcpy(bad_tag, tag, sizeof bad_tag);
    bad_tag[0] ^= 0x01u;
    memcpy(working, wire, sizeof working);
    CHECK(aead_open(key, nonce, aad, sizeof aad,
                    working, sizeof working, bad_tag) != 0);
    CHECK(memcmp(working, wire, sizeof working) == 0); /* not decrypted */

    /* A valid frame immediately after a rejection still opens. */
    CHECK(aead_open(key, nonce, aad, sizeof aad,
                    wire, sizeof wire, tag) == 0);
    CHECK(memcmp(wire, plain, sizeof wire) == 0);
}

/* Exhaustive single-bit tamper sweep over tag, AAD and ciphertext. */
static void test_single_bit_tamper(void) {
    static const uint8_t key[AEAD_KEY_BYTES] = {
        0x00,0x01,0x02,0x03,0x04,0x05,0x06,0x07,
        0x08,0x09,0x0a,0x0b,0x0c,0x0d,0x0e,0x0f,
        0x10,0x11,0x12,0x13,0x14,0x15,0x16,0x17,
        0x18,0x19,0x1a,0x1b,0x1c,0x1d,0x1e,0x1f
    };
    static const uint8_t nonce[AEAD_NONCE_BYTES] = {
        0x01,0x02,0x03,0x04,0x05,0x06,0x07,0x08,0x09,0x0a,0x0b,0x0c
    };
    uint8_t aad[AEAD_AAD_BYTES], wire[21], tag[AEAD_TAG_BYTES];
    uint8_t bad_aad[AEAD_AAD_BYTES], bad_wire[21], bad_tag[AEAD_TAG_BYTES];
    size_t i;
    unsigned bit;

    for (i = 0u; i < sizeof aad; i++) aad[i] = (uint8_t)i;
    for (i = 0u; i < sizeof wire; i++) wire[i] = (uint8_t)(0x40u + (uint8_t)i);
    aead_seal(key, nonce, aad, sizeof aad, wire, sizeof wire, tag);

    for (i = 0u; i < sizeof bad_tag; i++) {
        for (bit = 0u; bit < 8u; bit++) {
            memcpy(bad_tag, tag, sizeof bad_tag);
            bad_tag[i] ^= (uint8_t)(1u << bit);
            CHECK(aead_open(key, nonce, aad, sizeof aad, wire, sizeof wire,
                            bad_tag) != 0);
        }
    }
    for (i = 0u; i < sizeof aad; i++) {
        for (bit = 0u; bit < 8u; bit++) {
            memcpy(bad_aad, aad, sizeof bad_aad);
            bad_aad[i] ^= (uint8_t)(1u << bit);
            CHECK(aead_open(key, nonce, bad_aad, sizeof bad_aad,
                            wire, sizeof wire, tag) != 0);
        }
    }
    for (i = 0u; i < sizeof wire; i++) {
        for (bit = 0u; bit < 8u; bit++) {
            memcpy(bad_wire, wire, sizeof bad_wire);
            bad_wire[i] ^= (uint8_t)(1u << bit);
            CHECK(aead_open(key, nonce, aad, sizeof aad,
                            bad_wire, sizeof bad_wire, tag) != 0);
        }
    }
    CHECK(aead_open(key, nonce, aad, sizeof aad,
                    wire, sizeof wire, tag) == 0);
}

static void test_self_test(void) {
    CHECK(aead_self_test() == true);
}

int main(void) {
    test_chacha20_block_kat();
    test_poly1305_keygen_kat();
    test_poly1305_kat();
    test_aead_kat_seal();
    test_aead_kat_open();
    test_suite_round_trip();
    test_verify_before_decrypt();
    test_single_bit_tamper();
    test_self_test();

    if (failures) {
        printf("aead: %d failure(s)\n", failures);
        return 1;
    }
    printf("aead: PASS\n");
    return 0;
}
