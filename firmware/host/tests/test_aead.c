static void test_poly1305_kat(void) {
    uint8_t tag[POLY1305_TAG_BYTES];

    poly1305(POLY1305_KEY, POLY1305_MSG, sizeof POLY1305_MSG, tag);
    CHECK(memcmp(tag, POLY1305_WANT, sizeof tag) == 0);

    /* A zero-length message is legal and must not dereference a NULL pointer. */
    poly1305(POLY1305_KEY, NULL, 0u, tag);
}

